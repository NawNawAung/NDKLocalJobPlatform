function savedLanguage() {
    if (typeof window === 'undefined') return 'en';
    try {
        const saved = localStorage.getItem('ndk-language');
        if (saved === 'my' || saved === 'en') return saved;
    } catch { /* Storage may be unavailable in private browsing. */ }
    return document.cookie.split('; ').some((part) => part === 'ndk_language=my') ? 'my' : 'en';
}

export const locale = ref(savedLanguage());

export function t(englishText) {
    return locale.value === 'my' ? (translations[englishText] ?? englishText) : englishText;
}

export function setLocale(language) {
    locale.value = language === 'my' ? 'my' : 'en';
    if (typeof window === 'undefined') return;
    try { localStorage.setItem('ndk-language', locale.value); } catch { /* Cookie remains a fallback. */ }
    const secureCookie = window.location.protocol === 'https:' ? '; Secure' : '';
    document.cookie = `ndk_language=${locale.value}; Path=/; Max-Age=31536000; SameSite=Lax${secureCookie}`;
    document.documentElement.lang = locale.value;
    document.body.dataset.locale = locale.value;
}

setLocale(locale.value);
